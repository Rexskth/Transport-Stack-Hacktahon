"""Phase 3: validation checks -> reports/validation.md and reports/*.png.

Usage: python -m crowding.validate
Checks: hourly peaks, weekday vs weekend, busiest corridors, week-to-week stability,
anomalous days, mean ride length, and where estimates are least reliable.
"""
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from . import model, pipeline, config as C

OUT = "reports"
lines = []


def md(s=""):
    lines.append(s)


def table(df, floatfmt=3):
    h = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns)
    rows = ["| " + " | ".join(f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v) for v in r) + " |"
            for r in df.itertuples(index=False)]
    return h + "\n" + "\n".join(rows)


def spearman(a, b):
    return a.rank().corr(b.rank())


def main():
    p = pipeline.prepare()
    df, counts, rs, base, F = p["df"], p["counts"], p["rs"], p["base"], p["F"]
    out = model.estimate(counts, rs, base, F, p["days"])
    md("# Validation report\n")
    md("Generated by `python -m crowding.validate` from the October 2026 ticket data and the static GTFS feed.\n")

    # 0. data coverage
    s = p["stats"]
    md("## 0. Coverage\n")
    md(f"- Tickets used: {s['tickets_in']:,}; placed on the GTFS stop order: {s['tickets_placed']:,} ({s['share_placed']:.1%}).")
    md(f"- Day types: {p['days'][0]} weekday-like days, {p['days'][1]} weekend-like days (holidays {', '.join(C.HOLIDAY_DATES)} counted as weekend-like).")
    first = out[out.source == "raw"]
    md(f"- Model cells: {len(out):,}; own-ticket (raw) cells: {len(first):,} ({len(first)/len(out):.1%}).\n")

    # 1. hourly profile
    md("## 1. Morning and evening peaks\n")
    tix = df.assign(day_type=np.where(df.is_weekend, "weekend", "weekday")).groupby(["day_type", "hour"]).passenger_count.sum()
    days_by = {"weekday": p["days"][0], "weekend": p["days"][1]}
    prof = tix.unstack(0)
    for c in prof: prof[c] = prof[c] / days_by[c]
    mod = out[out.source == "raw"].assign(day_type=lambda x: np.where(x.is_weekend, "weekend", "weekday")) \
        .groupby(["day_type", "hour"]).riders_per_bus.mean().unstack(0)
    wk = prof.weekday
    am, pm = wk.loc[6:11].idxmax(), wk.loc[15:21].idxmax()
    mid = wk.loc[12:15].mean()
    md(f"- Weekday ticket peak hours: **{am}:00** (morning) and **{pm}:00** (evening). Midday (12-15h) average is {mid/wk.max():.0%} of the peak. "
       f"Check passes: {'yes' if 7 <= am <= 10 and 17 <= pm <= 20 else 'NO'}.")
    mpk = mod.weekday
    md(f"- Model riders per bus (raw cells, weekday) peaks at **{mpk.loc[6:11].idxmax()}:00** and **{mpk.loc[15:21].idxmax()}:00**.\n")
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.4))
    prof.plot(ax=ax[0], title="Tickets per day by hour"); ax[0].set_xlabel("hour")
    mod.plot(ax=ax[1], title="Model: mean riders per bus (raw cells)"); ax[1].set_xlabel("hour")
    plt.tight_layout(); plt.savefig(f"{OUT}/hourly_profile.png", dpi=110); plt.close()
    md("![hourly profile](hourly_profile.png)\n")

    # 2. weekday vs weekend
    md("## 2. Weekday vs weekend\n")
    d = df.groupby("date").passenger_count.sum()
    dd = pd.DataFrame({"pax": d, "dow": pd.to_datetime(d.index).day_of_week})
    byd = dd.groupby("dow").pax.mean().round(0).astype(int)
    names = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    md("Mean daily passengers by weekday (all days): " + ", ".join(f"{names[i]} {v:,}" for i, v in byd.items()) + ".\n")
    md(f"- Weekday-like day: {prof.weekday.sum():,.0f} passengers/day; weekend-like: {prof.weekend.sum():,.0f} "
       f"({prof.weekend.sum()/prof.weekday.sum():.0%} of weekday). Sunday is the lowest day: {'yes' if byd.idxmin() == 6 else 'NO'}.")
    cmp = out.groupby("is_weekend").riders_per_bus.mean()
    md(f"- Model mean riders per bus: weekday {cmp[False]:.3f}, weekend {cmp[True]:.3f} (weekend lower: {'yes' if cmp[True] < cmp[False] else 'NO'}).\n")

    # 3. busiest corridors
    md("## 3. Busiest corridors\n")
    vol = df.groupby("route").passenger_count.sum().sort_values(ascending=False)
    hi = out[(out.source == "raw") & (out.confidence == "high") & (~out.is_weekend)]
    peak = hi[hi.hour.isin([8, 9, 18, 19])]
    rt = peak.groupby("route").riders_per_bus.mean().sort_values(ascending=False)
    md("Top 10 routes by total tickets: " + ", ".join(vol.index[:10]) + ".\n")
    md("Top 10 routes by weekday peak riders per bus (high-confidence cells only):\n")
    md(table(rt.head(10).rename("riders_per_bus").reset_index()) + "\n")
    both = pd.concat([vol.rename("v"), rt.rename("r")], axis=1).dropna()
    tr = peak.groupby("route").trips.mean()
    md(f"Spearman correlation between route ticket volume and peak riders per bus: {spearman(both.v, both.r):.2f} (n={len(both)}). "
       f"The two are {'essentially uncorrelated' if abs(spearman(both.v, both.r)) < 0.1 else 'correlated'}: busy routes also run more buses, which lowers riders per bus; "
       f"peak riders per bus vs scheduled buses per hour: {spearman(rt, tr.reindex(rt.index)):.2f}. "
       f"Per-bus figures use at least {C.MIN_TRIPS_PER_HOUR} buses per hour and thinner cells are marked low confidence, "
       "because before this floor the top of the ranking was routes with 1-2 scheduled buses an hour. "
       "Routes at the top may still be genuinely crowded infrequent services, or services the GTFS schedule undercounts.\n")
    st = peak[peak.hour == 18].sort_values("riders_per_bus", ascending=False).head(10)
    md("Top 10 route stretches at 18:00 on weekdays (high confidence):\n")
    md(table(st[["route", "from_stop", "to_stop", "riders_per_bus", "level"]]) + "\n")

    # 4. week-to-week stability
    md("## 4. Week-to-week stability (weekdays, weeks 1-4)\n")
    est = {}
    for w in (1, 2, 3, 4):
        dw = pipeline.days_in_week(df, w)
        e = model.estimate(counts[counts.week == w], rs, base, F, dw)
        est[w] = e[~e.is_weekend]
    rows = []
    for a in (1, 2, 3, 4):
        for b in range(a + 1, 5):
            key = ["route", "stretch", "hour"]
            m = est[a].merge(est[b], on=key, suffixes=("_a", "_b"))
            raw = m[(m.source_a == "raw") & (m.source_b == "raw")]
            rh = lambda e: e.groupby(["route", "hour"]).riders_per_bus.mean()
            r = pd.concat([rh(est[a]), rh(est[b])], axis=1, keys=["a", "b"]).dropna()
            rows.append((f"{a} vs {b}", len(raw), spearman(raw.riders_per_bus_a, raw.riders_per_bus_b),
                         (raw.level_a == raw.level_b).mean(), len(r), spearman(r.a, r.b)))
    stab = pd.DataFrame(rows, columns=["weeks", "cells_raw_both", "spearman_cell", "same_level", "route_hours", "spearman_route_hour"])
    md(table(stab) + "\n")
    md(f"Mean Spearman: {stab.spearman_cell.mean():.2f} at stretch level (own tickets in both weeks), "
       f"{stab.spearman_route_hour.mean():.2f} at route-hour level; same crowding level in {stab.same_level.mean():.0%} of cells. "
       "Both figures are optimistic: the stretch-level numbers only cover cells with enough tickets in both weeks, and the route-hour numbers include route-average fallback values that agree by construction. "
       "Thinly sampled cells (60% of the model) are not covered by this check.\n")

    # 5. anomalous days
    md("## 5. Anomalous days\n")
    dd["typical"] = dd.groupby("dow").pax.transform("median")
    dd["ratio"] = dd.pax / dd.typical
    dd["flag"] = np.where(dd.ratio < 0.65, "LOW", "")
    md("Days whose volume is under 65% of the median for the same weekday are flagged and treated as holiday-like:\n")
    md(table(dd[dd.ratio < 0.8].assign(date=lambda x: x.index.astype(str), dow=lambda x: x.dow.map(dict(enumerate(names))))[["date", "dow", "pax", "ratio", "flag"]].reset_index(drop=True)) + "\n")
    fig, ax = plt.subplots(figsize=(10, 3.2))
    ax.bar(range(len(dd)), dd.pax, color=["tab:red" if f else "tab:blue" for f in dd.flag])
    ax.set_xticks(range(len(dd))); ax.set_xticklabels([str(i)[8:] for i in dd.index], fontsize=7)
    ax.set_title("Daily passengers (red = flagged low)"); plt.tight_layout(); plt.savefig(f"{OUT}/daily_totals.png", dpi=110); plt.close()
    md("![daily totals](daily_totals.png)\n")

    # 6. plausibility of ride length
    md("## 6. Ride length sanity\n")
    t = p["t"]; span = (t.e_pos - t.s_pos)
    md(f"Placed tickets span a median of {span.median():.0f} stops (mean {span.mean():.1f}, 90th percentile {span.quantile(.9):.0f}). "
       "This looks plausible for Delhi bus rides and shows stop matching is not producing absurd spans, but it is not a proof of correct matching.\n")

    # 7. reliability
    md("## 7. Where estimates are least reliable\n")
    md("Confidence by source:\n")
    md(table(pd.crosstab(out.source, out.confidence, normalize="all").round(3).reset_index()) + "\n")
    lowh = out.assign(low=out.confidence == "low").groupby("hour").low.mean()
    md(f"- Share of low-confidence cells by hour is highest at {lowh.idxmax()}:00 ({lowh.max():.0%}) and lowest at {lowh.idxmin()}:00 ({lowh.min():.0%}); "
       f"overall {lowh.mean():.0%}. Late-night and early-morning hours are the weakest.")
    q = pd.qcut(vol.rank(method="first"), 4, labels=["smallest", "small", "large", "largest"])
    byq = out.assign(q=out.route.map(q), low=out.confidence == "low").groupby("q", observed=True).low.mean()
    md("- Low-confidence share by route size (ticket volume quartile): " + ", ".join(f"{k} {v:.0%}" for k, v in byq.items()) + ".")
    md(f"- {1 - s['share_placed']:.1%} of tickets could not be placed (unmatched stop names or wrong direction); routes with poor stop naming are under-counted.")
    md("- Ticket data is a sample with no pass holders or bus size; levels are relative, not headcounts (see `crowding/config.py`).")
    md("- Scheduled frequency assumes every trip runs the full route and ignores actual delays; no real-time data is used.\n")

    open(f"{OUT}/validation.md", "w").write("\n".join(lines))
    print("wrote reports/validation.md")


if __name__ == "__main__":
    main()
